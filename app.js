let currentLang = 'en';

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  if (translations[lang] && translations[lang].page_title) {
    document.title = translations[lang].page_title;
  }

  const label = document.getElementById('langLabel');
  if (label) {
    label.textContent = lang === 'en' ? 'عربي' : 'EN';
  }

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  const form = document.getElementById('consultationForm');
  if (form) {
    const nameInput = form.querySelector('input[type="text"]');
    const textarea = form.querySelector('textarea');
    if (nameInput) {
      nameInput.placeholder = lang === 'ar' ? 'الاسم الكريم (م. / أ. / د.)' : 'Your Name (Eng. / Mr. / Dr.)';
    }
    if (textarea) {
      textarea.placeholder = lang === 'ar' 
        ? 'يرجى توضيح الطاقة الإنتاجية المستهدفة، الخدمات المطلوبة (تصميم، توريد، تركيب...)، والجدول الزمني...'
        : 'Briefly describe your required feed mill capacity, services (design, manufacturing, supply, erection), and timeline...';
    }
  }

  try {
    localStorage.setItem('bedaya_lang', lang);
  } catch (e) {}
}

window.addEventListener('scroll', () => {
  const header = document.getElementById('siteHeader');
  if (header) {
    if (window.scrollY > 40) {
      header.classList.add('scrolled');
    } else {
      header.classList.remove('scrolled');
    }
  }

  const sections = document.querySelectorAll('section[id]');
  const scrollY = window.pageYOffset + 140;

  sections.forEach(current => {
    const sectionHeight = current.offsetHeight;
    const sectionTop = current.offsetTop;
    const sectionId = current.getAttribute('id');
    const navLink = document.querySelector('.nav-menu a[href*=' + sectionId + ']');

    if (navLink) {
      if (scrollY > sectionTop && scrollY <= sectionTop + sectionHeight) {
        document.querySelectorAll('.nav-menu a').forEach(a => a.classList.remove('active'));
        navLink.classList.add('active');
      }
    }
  });
});

function initCounterAnimation() {
  const counters = document.querySelectorAll('.counter');
  let animated = false;

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting && !animated) {
        animated = true;
        counters.forEach(counter => {
          const target = +counter.getAttribute('data-target');
          const duration = 1600;
          const startTime = performance.now();

          function updateCount(currentTime) {
            const elapsed = currentTime - startTime;
            const progress = Math.min(elapsed / duration, 1);
            const current = Math.floor(progress * (2 - progress) * target);
            counter.innerText = current;

            if (progress < 1) {
              requestAnimationFrame(updateCount);
            } else {
              counter.innerText = target;
            }
          }
          requestAnimationFrame(updateCount);
        });
      }
    });
  }, { threshold: 0.3 });

  const statsSection = document.querySelector('.stats-bar-section');
  if (statsSection) {
    observer.observe(statsSection);
  }
}

function openPortfolioModal(country, count) {
  const modal = document.getElementById('portfolioModal');
  const title = document.getElementById('modalCountryTitle');
  const countEl = document.getElementById('modalProjectCount');
  
  if (currentLang === 'ar') {
    const arNames = {
      'Egypt': 'محفظة مشروعات جمهورية مصر العربية',
      'Oman': 'محفظة مشروعات سلطنة عُمان',
      'Saudi Arabia': 'محفظة مشروعات المملكة العربية السعودية',
      'UAE': 'محفظة مشروعات دولة الإمارات العربية المتحدة',
      'Regional (Egypt & Gulf)': 'محفظة المشروعات الإقليمية (مصر والخليج)'
    };
    title.textContent = arNames[country] || country;
    countEl.textContent = count.replace('Projects', 'مشروعات').replace('Project', 'مشروع');
  } else {
    title.textContent = country + " Regional Portfolio";
    countEl.textContent = count + " Executed Installations";
  }

  if (modal) modal.classList.add('active');
}

function closePortfolioModal() {
  const modal = document.getElementById('portfolioModal');
  if (modal) modal.classList.remove('active');
}

document.addEventListener('DOMContentLoaded', () => {
  const langToggle = document.getElementById('langToggle');
  if (langToggle) {
    langToggle.addEventListener('click', () => {
      setLanguage(currentLang === 'en' ? 'ar' : 'en');
    });
  }

  const mobileToggle = document.getElementById('mobileToggle');
  const navMenu = document.getElementById('navMenu');
  if (mobileToggle && navMenu) {
    mobileToggle.addEventListener('click', () => {
      navMenu.classList.toggle('mobile-open');
    });
    navMenu.querySelectorAll('a').forEach(link => {
      link.addEventListener('click', () => {
        navMenu.classList.remove('mobile-open');
      });
    });
  }

  const closeModalBtn = document.getElementById('closeModalBtn');
  const modal = document.getElementById('portfolioModal');
  if (closeModalBtn) {
    closeModalBtn.addEventListener('click', closePortfolioModal);
  }
  if (modal) {
    modal.addEventListener('click', (e) => {
      if (e.target === modal) closePortfolioModal();
    });
  }

  const openProjectsModalBtn = document.getElementById('openProjectsModalBtn');
  if (openProjectsModalBtn) {
    openProjectsModalBtn.addEventListener('click', () => {
      openPortfolioModal('Regional (Egypt & Gulf)', '30+ Projects');
    });
  }

  const reachRows = document.querySelectorAll('.reach-stat-row');
  reachRows.forEach(row => {
    row.addEventListener('mouseenter', () => {
      reachRows.forEach(r => r.classList.remove('active'));
      row.classList.add('active');
      const key = row.getAttribute('data-country-key');
      document.querySelectorAll('.map-country-path').forEach(p => p.style.opacity = '0.45');
      const activePath = document.getElementById('map-' + key);
      if (activePath) {
        activePath.style.opacity = '1';
        activePath.style.fill = '#423820';
      }
    });
    row.addEventListener('mouseleave', () => {
      document.querySelectorAll('.map-country-path').forEach(p => {
        p.style.opacity = '1';
        p.style.fill = '';
      });
    });
  });

  const consultationForm = document.getElementById('consultationForm');
  const formToast = document.getElementById('formToast');
  if (consultationForm) {
    consultationForm.addEventListener('submit', (e) => {
      e.preventDefault();
      const submitBtn = consultationForm.querySelector('button[type="submit"]');
      submitBtn.disabled = true;
      submitBtn.style.opacity = '0.7';
      submitBtn.innerText = currentLang === 'ar' ? 'جارٍ تسجيل الطلب...' : 'Processing Inquiry...';

      setTimeout(() => {
        submitBtn.disabled = false;
        submitBtn.style.opacity = '1';
        submitBtn.innerText = currentLang === 'ar' ? 'تم إرسال الطلب بنجاح ✓' : 'Inquiry Submitted ✓';
        if (formToast) {
          formToast.style.display = 'block';
        }
        consultationForm.reset();
      }, 700);
    });
  }

  const savedLang = localStorage.getItem('bedaya_lang') || 'en';
  setLanguage(savedLang);

  initCounterAnimation();
});
